"""The methods note must quote only figures the repository's data produces.

Section 4 of ``docs/methods-note.md`` is a block generated by
``tools/methods_note_stats.py``. These tests regenerate it and compare, and also
check the headline figures written into the note's prose against the data.
"""

from __future__ import annotations

import os
import re
import unittest

from tests import context

from tools import methods_note_stats as stats

NOTE_PATH = os.path.join(context.REPO_ROOT, "docs", "methods-note.md")


def _note() -> str:
    with open(NOTE_PATH, encoding="utf-8") as handle:
        return handle.read()


class TestMethodsNote(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.ontology = context.ontology()
        cls.figures = stats.compute(cls.ontology)
        cls.text = _note()

    def test_generated_block_is_current(self) -> None:
        block = stats.render(self.figures, self.ontology)
        start = self.text.index(stats.BEGIN_MARKER)
        end = self.text.index(stats.END_MARKER) + len(stats.END_MARKER)
        self.assertEqual(
            self.text[start:end],
            block,
            "docs/methods-note.md is stale; run python3 tools/methods_note_stats.py --write",
        )

    def test_abstract_figures_match_data(self) -> None:
        abstract = self.text.split("## Abstract", 1)[1].split("## 1", 1)[0]
        abstract = " ".join(abstract.split())
        self.assertIn(f"the {self.figures['factors']} performance-influencing", abstract)
        self.assertIn(f"({self.figures['alignments']} factor-level alignments", abstract)

    def test_no_exact_matches_claimed(self) -> None:
        total_exact = sum(c["exact"] for c in self.figures["by_fw_strength"].values())
        self.assertEqual(total_exact, 0)
        self.assertIn("no alignment is claimed as exact", self.text)

    def test_coverage_rows_account_for_every_entry(self) -> None:
        for row in self.figures["coverage"]:
            accounted = row["aligned"] + row["gap"] - row["gap_and_aligned"] + row["out_of_scope"]
            self.assertEqual(accounted, row["inventory"], row["framework"])

    def test_prose_claims_match_data(self) -> None:
        reach = self.figures["reach"]
        self.assertEqual(min(reach), 3)
        self.assertIn("counterpart in at least three of the four frameworks", self.text)
        sparh = [f for f, fw in self.figures["no_counterpart"] if fw == "SPAR-H"]
        dims = {
            self.ontology.factors[c].dimension
            for c in self.ontology.factors
            if self.ontology.factors[c].label in sparh
        }
        self.assertEqual(dims, {"ehs:OperationalContext"})
        self.assertEqual(len(sparh), 5)
        self.assertIn("All five asserted absences against SPAR-H", self.text)
        levels = self.figures["example"].scenario.factor_levels.values()
        self.assertEqual(sum(v == "ehs:LevelNominal" for v in levels), 16)
        self.assertIn("the other sixteen factors as nominal", self.text)

    def test_no_em_dashes(self) -> None:
        self.assertNotIn("—", self.text)

    def test_readme_links_note(self) -> None:
        with open(os.path.join(context.REPO_ROOT, "README.md"), encoding="utf-8") as handle:
            self.assertTrue(re.search(r"\(docs/methods-note\.md\)", handle.read()))


if __name__ == "__main__":
    unittest.main()
