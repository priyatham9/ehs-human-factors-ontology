#!/usr/bin/env python3
"""Compute the results section of ``docs/methods-note.md`` from the repository.

Every number in section 4 of the methods note is produced here, from the
ontology, the rule base and the worked example, so the note cannot quote a
figure the data does not support. The script renders a Markdown block and the
note carries that block verbatim between two marker comments.

``tests/test_methods_note.py`` regenerates the block and fails if the copy in
the note differs.

Usage::

    python3 tools/methods_note_stats.py            # print the block
    python3 tools/methods_note_stats.py --write    # refresh the note in place
    python3 tools/methods_note_stats.py --check    # exit 1 if the note is stale
"""

from __future__ import annotations

import argparse
import os
import sys
from collections import Counter
from typing import Dict, List, Optional, Tuple

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_REPO_ROOT, "src"))

from ehs_hfo.assessment import assess  # noqa: E402
from ehs_hfo.facts import Scenario  # noqa: E402
from ehs_hfo.ontology import Ontology  # noqa: E402
from ehs_hfo.rules import RULES, build_program  # noqa: E402

__all__ = ["compute", "render", "NOTE_PATH", "BEGIN_MARKER", "END_MARKER"]

NOTE_PATH = os.path.join(_REPO_ROOT, "docs", "methods-note.md")
EXAMPLE_PATH = os.path.join(_REPO_ROOT, "examples", "reactor_startup_nonroutine.json")
BEGIN_MARKER = "<!-- BEGIN GENERATED BY tools/methods_note_stats.py; do not hand-edit -->"
END_MARKER = "<!-- END GENERATED -->"

#: Factor-level frameworks, in the order the crosswalk tables use.
FRAMEWORKS: Tuple[Tuple[str, str], ...] = (
    ("xw:fw-SPARH", "SPAR-H"),
    ("xw:fw-CREAM", "CREAM"),
    ("xw:fw-HFACS", "HFACS"),
    ("xw:fw-HSE-PIF", "HSE PIF list"),
)
IDHEAS = ("xw:fw-IDHEAS-G", "IDHEAS-G")
STRENGTHS: Tuple[str, ...] = ("close", "broader", "narrower", "partial", "exact")


def _strength(curie: str) -> str:
    return curie.split(":")[-1].replace("Match", "").lower()


def compute(ontology: Optional[Ontology] = None) -> Dict[str, object]:
    """Every figure the note reports, as plain Python values."""
    ontology = ontology or Ontology.load()
    alignments = list(ontology.alignments.values())
    ext = ontology.external_factors

    by_fw_strength: Dict[str, Counter] = {fw: Counter() for fw, _ in FRAMEWORKS}
    for a in alignments:
        by_fw_strength[ext[a.external_factor].framework][_strength(a.match_strength)] += 1

    by_dimension: Counter = Counter(
        ontology.factors[a.local_factor].dimension for a in alignments
    )

    no_counterpart: List[Tuple[str, str]] = sorted(
        (ontology.factors[f].label, dict(FRAMEWORKS)[fw])
        for f, fws in ontology.no_counterpart.items()
        for fw in fws
    )

    aligned_ext = {a.external_factor for a in alignments}
    gap_ext = {g.uncovered_factor for g in ontology.coverage_gaps.values()}
    coverage = []
    for fw, label in FRAMEWORKS + (IDHEAS,):
        inventory = ontology.external_factors_of(fw)
        coverage.append(
            {
                "framework": label,
                "inventory": len(inventory),
                "aligned": sum(e.curie in aligned_ext for e in inventory),
                "gap": sum(e.curie in gap_ext for e in inventory),
                "gap_and_aligned": sum(
                    e.curie in gap_ext and e.curie in aligned_ext for e in inventory
                ),
                "out_of_scope": sum(bool(e.out_of_scope_note) for e in inventory),
            }
        )

    gaps = sorted(
        (ext[g.uncovered_factor].label, dict(FRAMEWORKS)[ext[g.uncovered_factor].framework],
         g.uncovered_factor in aligned_ext)
        for g in ontology.coverage_gaps.values()
    )

    frameworks_per_factor: Dict[str, int] = {}
    for f in ontology.factors:
        frameworks_per_factor[f] = len(
            {ext[a.external_factor].framework for a in ontology.alignments_for(f)}
        )
    reach = Counter(frameworks_per_factor.values())

    per_factor = Counter(a.local_factor for a in alignments)
    most = max(per_factor.values())
    most_aligned = sorted(ontology.factors[f].label for f, n in per_factor.items() if n == most)

    basis = Counter(r.basis for r in RULES)

    scenario = Scenario.from_json_file(EXAMPLE_PATH)
    result = assess(scenario, ontology=ontology, program=build_program())

    return {
        "factors": len(ontology.factors),
        "dimensions": len(ontology.dimensions),
        "alignments": len(alignments),
        "external_factors": len(ext),
        "by_fw_strength": by_fw_strength,
        "by_dimension": by_dimension,
        "no_counterpart": no_counterpart,
        "coverage": coverage,
        "gaps": gaps,
        "reach": reach,
        "most_aligned": (most, most_aligned),
        "min_per_factor": min(per_factor.values()),
        "rules": len(RULES),
        "rule_basis": basis,
        "example": result,
    }


def render(stats: Optional[Dict[str, object]] = None, ontology: Optional[Ontology] = None) -> str:
    """The generated Markdown block, markers included."""
    ontology = ontology or Ontology.load()
    s = stats or compute(ontology)
    out: List[str] = [BEGIN_MARKER, ""]

    totals: Counter = Counter()
    out.append("**Table 1. Alignments by framework and match strength.**")
    out.append("")
    out.append("| Framework | close | broader | narrower | partial | exact | Total |")
    out.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for fw, label in FRAMEWORKS:
        c = s["by_fw_strength"][fw]
        totals.update(c)
        cells = " | ".join(str(c[k]) for k in STRENGTHS)
        out.append(f"| {label} | {cells} | {sum(c.values())} |")
    cells = " | ".join(str(totals[k]) for k in STRENGTHS)
    out.append(f"| **All** | {cells} | {sum(totals.values())} |")
    out.append("")

    out.append("**Table 2. Alignments by context dimension.**")
    out.append("")
    out.append("| Dimension | IDHEAS-G category | Factors | Alignments |")
    out.append("| --- | --- | ---: | ---: |")
    for curie in sorted(ontology.dimensions, key=lambda c: ontology.dimensions[c].label):
        d = ontology.dimensions[curie]
        idheas = ontology.external_factors[d.idheas_category].label if d.idheas_category else ""
        out.append(
            f"| {d.label} | {idheas} | {len(ontology.factors_in(curie))} "
            f"| {s['by_dimension'][curie]} |"
        )
    out.append("")

    out.append("**Table 3. Coverage of each external inventory.** An entry can be both")
    out.append("aligned and recorded as a gap when the only alignment is partial and the")
    out.append("construct itself is judged missing.")
    out.append("")
    out.append(
        "| Framework | Entries | Aligned to a local factor | Recorded gap "
        "| Gap and aligned | Out of scope |"
    )
    out.append("| --- | ---: | ---: | ---: | ---: | ---: |")
    for row in s["coverage"]:
        out.append(
            f"| {row['framework']} | {row['inventory']} | {row['aligned']} | {row['gap']} "
            f"| {row['gap_and_aligned']} | {row['out_of_scope']} |"
        )
    out.append("")

    out.append("**Table 4. Local factors with an asserted absence in a framework.**")
    out.append("")
    out.append("| Local factor | Framework with no counterpart |")
    out.append("| --- | --- |")
    for factor, fw in s["no_counterpart"]:
        out.append(f"| {factor} | {fw} |")
    out.append("")

    out.append("**Table 5. External entries recorded as coverage gaps.**")
    out.append("")
    out.append("| External entry | Framework | Also has a partial alignment |")
    out.append("| --- | --- | --- |")
    for label, fw, aligned in s["gaps"]:
        out.append(f"| {label} | {fw} | {'yes' if aligned else 'no'} |")
    out.append("")

    reach = s["reach"]
    most, most_labels = s["most_aligned"]
    out.append("**Summary figures.**")
    out.append("")
    out.append(f"- Local factors: {s['factors']} in {s['dimensions']} context dimensions.")
    out.append(
        f"- External entries transcribed: {s['external_factors']} across "
        f"{len(FRAMEWORKS) + 1} frameworks."
    )
    out.append(f"- Factor-level alignments: {s['alignments']}.")
    out.append(f"- Asserted absences (no counterpart): {len(s['no_counterpart'])}.")
    for k in sorted(reach, reverse=True):
        out.append(f"- Local factors aligned in {k} of {len(FRAMEWORKS)} frameworks: {reach[k]}.")
    out.append(
        f"- Local factors with no counterpart in any of the {len(FRAMEWORKS)} "
        f"frameworks: {reach.get(0, 0)}."
    )
    out.append(
        f"- Alignments per local factor: minimum {s['min_per_factor']}, maximum {most} "
        f"({', '.join(most_labels)})."
    )
    basis = s["rule_basis"]
    out.append(
        f"- Rules: {s['rules']}, of which {basis['literature']} are marked `literature` "
        f"and {basis['convention']} `convention`."
    )
    out.append("")

    ex = s["example"]
    fac = ontology.factors
    assessed, total = ex.coverage
    out.append("**Worked example output** (`examples/reactor_startup_nonroutine.json`).")
    out.append("")
    out.append(f"- Factors assessed: {assessed} of {total}.")
    out.append(f"- Screening band: `{ex.screening_band}`.")
    out.append(
        "- Aggravated failure modes: "
        + ", ".join(ontology.failure_modes[k].label for _, k in ex.aggravated_failure_modes)
        + "."
    )
    out.append(
        "- Aggravated error modes: "
        + ", ".join(ontology.error_modes[m].label for m in ex.aggravated_error_modes)
        + "."
    )
    out.append(
        "- Unsupported control demands: "
        + ", ".join(ontology._label(ontology.graph.expand(c)) for c in ex.unsupported_demands)
        + "."
    )
    out.append(
        "- Degraded factors with no mitigation claimed: "
        + ", ".join(fac[f].label for f in ex.unmitigated)
        + "."
    )
    out.append(f"- Distinct rules fired: {len(ex.result.rules_fired())} of {s['rules']}.")
    out.append("")
    out.append(END_MARKER)
    return "\n".join(out)


def _replace_block(text: str, block: str) -> str:
    start = text.index(BEGIN_MARKER)
    end = text.index(END_MARKER) + len(END_MARKER)
    return text[:start] + block + text[end:]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="refresh the note in place")
    group.add_argument("--check", action="store_true", help="exit 1 if the note is stale")
    args = parser.parse_args(argv)

    block = render()
    if not (args.write or args.check):
        print(block)
        return 0
    with open(NOTE_PATH, encoding="utf-8") as handle:
        text = handle.read()
    updated = _replace_block(text, block)
    if args.check:
        if updated != text:
            print("docs/methods-note.md is out of date; run with --write", file=sys.stderr)
            return 1
        return 0
    with open(NOTE_PATH, "w", encoding="utf-8") as handle:
        handle.write(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
