#!/usr/bin/env python3
"""PIF co-occurrence network across the coded CSB investigations (stdlib only).

Input: ``incidents/csb_coding.csv`` (investigation x PIF codings) and the
ontology (for the number of PIFs). Output: two CSV files in ``incidents/``, an
SVG heat map and a generated results block in ``docs/pif-cooccurrence.md``.

Method. Each coded investigation is the set of PIFs coded to it. Two PIFs
co-occur when both are coded to the same investigation. Observed pair counts
are compared with a null that keeps every investigation's number of PIFs and
every PIF's number of investigations fixed (swap randomisation: repeated
exchanges of one PIF between two investigations). Upper- and lower-tail
permutation p-values use the +1 correction; Holm adjustment is applied over
all pairs. PIF prevalence has Wilson 95% intervals; weighted degree (sum of
co-occurrences) has bootstrap-over-investigations 95% percentile intervals.
Everything is seeded and deterministic.

Usage::

    python3 tools/pif_cooccurrence.py            # print the results block
    python3 tools/pif_cooccurrence.py --write    # refresh CSVs, SVG and doc
    python3 tools/pif_cooccurrence.py --check    # exit 1 if any output is stale
"""

from __future__ import annotations

import argparse
import csv
import io
import math
import os
import random
import sys
from collections import defaultdict
from itertools import combinations
from typing import Dict, List, Sequence, Tuple

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODING_PATH = os.path.join(_REPO_ROOT, "incidents", "csb_coding.csv")
PAIRS_PATH = os.path.join(_REPO_ROOT, "incidents", "pif_cooccurrence_pairs.csv")
PIFS_PATH = os.path.join(_REPO_ROOT, "incidents", "pif_cooccurrence_pifs.csv")
SVG_PATH = os.path.join(_REPO_ROOT, "docs", "pif-cooccurrence.svg")
DOC_PATH = os.path.join(_REPO_ROOT, "docs", "pif-cooccurrence.md")
BEGIN_MARKER = "<!-- BEGIN GENERATED BY tools/pif_cooccurrence.py; do not hand-edit -->"
END_MARKER = "<!-- END GENERATED -->"

SEED = 20261106
N_NULL = 4000
SWAPS_BETWEEN = 400
BURN_IN = 4000
N_BOOT = 2000

__all__ = ["compute", "render_block", "render_svg", "pairs_csv", "pifs_csv"]


def load_sets(path: str = CODING_PATH) -> Dict[str, frozenset]:
    sets: Dict[str, set] = defaultdict(set)
    with open(path, encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            sets[row["investigation_id"]].add(row["factor_curie"])
    return {k: frozenset(v) for k, v in sorted(sets.items())}


def ontology_pif_count() -> int:
    sys.path.insert(0, os.path.join(_REPO_ROOT, "src"))
    from ehs_hfo.ontology import Ontology

    return len(Ontology.load().factors)


def wilson(k: int, n: int, z: float = 1.959964) -> Tuple[float, float]:
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return centre - half, centre + half


def _pair_counts(rows: Sequence[Sequence[str]]) -> Dict[Tuple[str, str], int]:
    counts: Dict[Tuple[str, str], int] = defaultdict(int)
    for row in rows:
        for a, b in combinations(sorted(row), 2):
            counts[(a, b)] += 1
    return counts


def _swap_null(rows: List[List[str]], rng: random.Random):
    """Yield margin-preserving randomisations of the investigation x PIF matrix."""
    rows = [list(r) for r in rows]
    n = len(rows)

    def step(count: int) -> None:
        for _ in range(count):
            i, j = rng.randrange(n), rng.randrange(n)
            if i == j:
                continue
            only_i = [x for x in rows[i] if x not in rows[j]]
            only_j = [x for x in rows[j] if x not in rows[i]]
            if not only_i or not only_j:
                continue
            x, y = rng.choice(only_i), rng.choice(only_j)
            rows[i][rows[i].index(x)] = y
            rows[j][rows[j].index(y)] = x

    step(BURN_IN)
    for _ in range(N_NULL):
        step(SWAPS_BETWEEN)
        yield rows


def _quantile(sorted_vals: Sequence[float], q: float) -> float:
    pos = q * (len(sorted_vals) - 1)
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    return sorted_vals[lo] + (sorted_vals[hi] - sorted_vals[lo]) * (pos - lo)


def _holm(pvals: Dict[Tuple[str, str], float]) -> Dict[Tuple[str, str], float]:
    order = sorted(pvals, key=lambda k: (pvals[k], k))
    m = len(order)
    out: Dict[Tuple[str, str], float] = {}
    running = 0.0
    for rank, key in enumerate(order):
        running = max(running, min(1.0, (m - rank) * pvals[key]))
        out[key] = running
    return out


def compute() -> Dict[str, object]:
    sets = load_sets()
    inv = list(sets)
    n = len(inv)
    rows = [sorted(sets[i]) for i in inv]
    pifs = sorted({p for r in rows for p in r})
    prevalence = {p: sum(p in r for r in rows) for p in pifs}
    all_pairs = list(combinations(pifs, 2))
    observed = _pair_counts(rows)
    obs = {pr: observed.get(pr, 0) for pr in all_pairs}
    obs_stat = sum(v * v for v in obs.values())

    rng = random.Random(SEED)
    ge = {pr: 1 for pr in all_pairs}
    le = {pr: 1 for pr in all_pairs}
    total = {pr: 0 for pr in all_pairs}
    stat_ge = 1
    for null_rows in _swap_null(rows, rng):
        c = _pair_counts(null_rows)
        s = 0
        for pr in all_pairs:
            v = c.get(pr, 0)
            total[pr] += v
            s += v * v
            if v >= obs[pr]:
                ge[pr] += 1
            if v <= obs[pr]:
                le[pr] += 1
        if s >= obs_stat:
            stat_ge += 1
    denom = N_NULL + 1
    p_up = {pr: ge[pr] / denom for pr in all_pairs}
    p_lo = {pr: le[pr] / denom for pr in all_pairs}
    p_two = {pr: min(1.0, 2 * min(p_up[pr], p_lo[pr])) for pr in all_pairs}
    holm = _holm(p_two)
    expected = {pr: total[pr] / N_NULL for pr in all_pairs}

    # Weighted degree: sum over investigations containing the PIF of (size - 1).
    def wdeg(sample: Sequence[Sequence[str]]) -> Dict[str, int]:
        d = {p: 0 for p in pifs}
        for r in sample:
            for p in r:
                d[p] += len(r) - 1
        return d

    wd = wdeg(rows)
    brng = random.Random(SEED + 1)
    boots = {p: [] for p in pifs}
    for _ in range(N_BOOT):
        d = wdeg([rows[brng.randrange(n)] for _ in range(n)])
        for p in pifs:
            boots[p].append(d[p])
    wd_ci = {}
    for p in pifs:
        vals = sorted(boots[p])
        wd_ci[p] = (_quantile(vals, 0.025), _quantile(vals, 0.975))

    return {
        "n_inv": n,
        "n_codings": sum(len(r) for r in rows),
        "n_pifs_total": ontology_pif_count(),
        "pifs": pifs,
        "prevalence": prevalence,
        "prev_ci": {p: wilson(prevalence[p], n) for p in pifs},
        "pairs": all_pairs,
        "obs": obs,
        "expected": expected,
        "p_up": p_up,
        "p_lo": p_lo,
        "holm": holm,
        "wdeg": wd,
        "wdeg_ci": wd_ci,
        "obs_stat": obs_stat,
        "p_stat": stat_ge / denom,
        "n_distinct": sum(1 for v in obs.values() if v > 0),
        "max_pair": max(all_pairs, key=lambda pr: (obs[pr], pr)),
    }


def short(curie: str) -> str:
    return curie.split(":", 1)[1]


def pifs_csv(fig: Dict[str, object]) -> str:
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["pif", "investigations", "prevalence", "prev_ci_low", "prev_ci_high",
                "weighted_degree", "wdeg_ci_low", "wdeg_ci_high"])
    for p in sorted(fig["pifs"], key=lambda p: (-fig["prevalence"][p], p)):
        lo, hi = fig["prev_ci"][p]
        dlo, dhi = fig["wdeg_ci"][p]
        w.writerow([short(p), fig["prevalence"][p], "%.4f" % (fig["prevalence"][p] / fig["n_inv"]),
                    "%.4f" % lo, "%.4f" % hi, fig["wdeg"][p], "%.1f" % dlo, "%.1f" % dhi])
    return out.getvalue()


def pairs_csv(fig: Dict[str, object]) -> str:
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["pif_a", "pif_b", "observed", "null_mean", "p_upper", "p_lower", "holm_p_two_sided"])
    for pr in sorted(fig["pairs"], key=lambda k: (-fig["obs"][k], fig["p_up"][k], k)):
        w.writerow([short(pr[0]), short(pr[1]), fig["obs"][pr], "%.3f" % fig["expected"][pr],
                    "%.4f" % fig["p_up"][pr], "%.4f" % fig["p_lo"][pr], "%.4f" % fig["holm"][pr]])
    return out.getvalue()


def render_block(fig: Dict[str, object]) -> str:
    n = fig["n_inv"]
    npairs = len(fig["pairs"])
    unadj = sum(1 for pr in fig["pairs"] if fig["p_up"][pr] <= 0.05)
    adj = sum(1 for pr in fig["pairs"] if fig["holm"][pr] <= 0.05)
    top = fig["max_pair"]
    lines = [BEGIN_MARKER, ""]
    lines.append(
        "- Data: %d codings over %d coded investigations; %d of the %d ontology PIFs appear "
        "at least once (%d PIFs never coded)."
        % (fig["n_codings"], n, len(fig["pifs"]), fig["n_pifs_total"],
           fig["n_pifs_total"] - len(fig["pifs"])))
    lines.append(
        "- %d of %d possible PIF pairs co-occur in at least one investigation."
        % (fig["n_distinct"], npairs))
    lines.append(
        "- Most frequent pair: %s + %s in %d investigations (null mean %.2f, upper-tail p = %.4f, "
        "Holm two-sided p = %.4f)."
        % (short(top[0]), short(top[1]), fig["obs"][top], fig["expected"][top],
           fig["p_up"][top], fig["holm"][top]))
    lines.append(
        "- Pairs with upper-tail p <= 0.05 before adjustment: %d of %d (about %.1f expected by "
        "chance alone); with Holm adjustment (two-sided): %d."
        % (unadj, npairs, 0.05 * npairs, adj))
    lines.append(
        "- Global concentration statistic (sum of squared pair counts): observed %d, "
        "upper-tail p = %.4f."
        % (fig["obs_stat"], fig["p_stat"]))
    lines.append("")
    lines.append("PIF prevalence and weighted degree (sum of co-occurrences; bootstrap 95% interval):")
    lines.append("")
    lines.append("| PIF | Investigations | Prevalence (Wilson 95%) | Weighted degree (bootstrap 95%) |")
    lines.append("|---|---:|---|---|")
    for p in sorted(fig["pifs"], key=lambda p: (-fig["prevalence"][p], p)):
        lo, hi = fig["prev_ci"][p]
        dlo, dhi = fig["wdeg_ci"][p]
        lines.append("| %s | %d | %.0f%% (%.0f%% to %.0f%%) | %d (%.0f to %.0f) |" % (
            short(p), fig["prevalence"][p], 100 * fig["prevalence"][p] / n, 100 * lo, 100 * hi,
            fig["wdeg"][p], dlo, dhi))
    lines.append("")
    lines.append("Five most frequent pairs:")
    lines.append("")
    lines.append("| Pair | Observed | Null mean | Upper-tail p | Holm two-sided p |")
    lines.append("|---|---:|---:|---:|---:|")
    ranked = sorted(fig["pairs"], key=lambda k: (-fig["obs"][k], fig["p_up"][k], k))[:5]
    for pr in ranked:
        lines.append("| %s + %s | %d | %.2f | %.4f | %.4f |" % (
            short(pr[0]), short(pr[1]), fig["obs"][pr], fig["expected"][pr],
            fig["p_up"][pr], fig["holm"][pr]))
    lines.append("")
    lines.append(END_MARKER)
    return "\n".join(lines)


def render_svg(fig: Dict[str, object]) -> str:
    pifs = sorted(fig["pifs"], key=lambda p: (-fig["prevalence"][p], p))
    k = len(pifs)
    cell, left, top = 44, 230, 40
    width = left + k * cell + 24
    height = top + k * cell + 90
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" '
        'role="img" aria-labelledby="t d" font-family="system-ui, sans-serif" font-size="12">'
        % (width, height, width, height),
        "<title id=\"t\">PIF co-occurrence across coded CSB investigations</title>",
        "<desc id=\"d\">Heat map of observed minus null-expected co-occurrence for each PIF pair; "
        "cell labels give the observed count. No pair is highlighted as significant.</desc>",
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        '<text x="%d" y="22" font-size="14" font-weight="600" fill="#1a1a1a">Observed co-occurrence '
        '(cell label) and excess over the swap-null mean (shade)</text>' % 8,
    ]
    for i, a in enumerate(pifs):
        y = top + i * cell + cell / 2 + 4
        out.append('<text x="%d" y="%d" text-anchor="end" fill="#1a1a1a">%s</text>'
                   % (left - 8, y, short(a)))
        for j, b in enumerate(pifs):
            x = left + j * cell
            yy = top + i * cell
            if i == j:
                out.append('<rect x="%d" y="%d" width="%d" height="%d" fill="#e5e5e5" '
                           'stroke="#ffffff"/>' % (x, yy, cell, cell))
                out.append('<text x="%d" y="%d" text-anchor="middle" fill="#1a1a1a">%d</text>'
                           % (x + cell / 2, yy + cell / 2 + 4, fig["prevalence"][a]))
                continue
            pr = (a, b) if (a, b) in fig["obs"] else (b, a)
            diff = fig["obs"][pr] - fig["expected"][pr]
            mag = min(1.0, abs(diff) / 2.0)
            if diff >= 0:
                colour = "#%02x%02x%02x" % (255 - int(185 * mag), 255 - int(135 * mag), 255 - int(35 * mag))
            else:
                colour = "#%02x%02x%02x" % (255, 255 - int(110 * mag), 255 - int(180 * mag))
            out.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" stroke="#ffffff"/>'
                       % (x, yy, cell, cell, colour))
            out.append('<text x="%d" y="%d" text-anchor="middle" fill="#1a1a1a">%d</text>'
                       % (x + cell / 2, yy + cell / 2 + 4, fig["obs"][pr]))
    for j, b in enumerate(pifs):
        x = left + j * cell + cell / 2
        out.append('<text transform="translate(%d,%d) rotate(-60)" fill="#1a1a1a" '
                   'text-anchor="end">%s</text>' % (x + 4, top + k * cell + 14, short(b)))
    out.append('<text x="8" y="%d" fill="#555555" font-size="11">Diagonal: investigations coding the '
               'PIF. Blue: more co-occurrence than the null mean; orange: less. '
               'Not a significance map.</text>' % (height - 8))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def doc_with_block(doc: str, block: str) -> str:
    start = doc.index(BEGIN_MARKER)
    end = doc.index(END_MARKER) + len(END_MARKER)
    return doc[:start] + block + doc[end:]


def main(argv: Sequence[str] = ()) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv or None)
    fig = compute()
    block = render_block(fig)
    targets = {PAIRS_PATH: pairs_csv(fig), PIFS_PATH: pifs_csv(fig), SVG_PATH: render_svg(fig)}
    if os.path.exists(DOC_PATH):
        with open(DOC_PATH, encoding="utf-8") as handle:
            targets[DOC_PATH] = doc_with_block(handle.read(), block)
    if args.write:
        for path, text in targets.items():
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
        return 0
    if args.check:
        stale = []
        for path, text in targets.items():
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != text:
                stale.append(os.path.relpath(path, _REPO_ROOT))
        if stale:
            print("stale: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
