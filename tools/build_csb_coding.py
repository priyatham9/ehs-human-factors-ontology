#!/usr/bin/env python3
"""Render ``incidents/csb_coding.md`` from the two CSVs in ``incidents/``.

Usage::

    python3 tools/build_csb_coding.py           # print
    python3 tools/build_csb_coding.py --write   # refresh incidents/csb_coding.md
"""

from __future__ import annotations

import csv
import os
import sys
from collections import Counter
from typing import Dict, List

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_REPO_ROOT, "src"))

from ehs_hfo.ontology import Ontology  # noqa: E402

INC_DIR = os.path.join(_REPO_ROOT, "incidents")
INVESTIGATIONS = os.path.join(INC_DIR, "csb_investigations.csv")
CODING = os.path.join(INC_DIR, "csb_coding.csv")
OUTPUT = os.path.join(INC_DIR, "csb_coding.md")


def read(path: str) -> List[Dict[str, str]]:
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def render(ont: Ontology) -> str:
    inv = read(INVESTIGATIONS)
    rows = read(CODING)
    by_id = {r["investigation_id"]: r for r in inv}
    coded = [r for r in inv if r["coded"] == "yes"]
    out = [
        "# CSB investigations coded to the PIF crosswalk",
        "",
        "Generated by `tools/build_csb_coding.py` from `csb_investigations.csv` and",
        "`csb_coding.csv`; do not hand-edit. Method and limits: `README.md` in this folder.",
        "",
        f"{len(coded)} of {len(inv)} listed investigations are coded; {len(rows)} codings.",
        "",
        "## Codings",
        "",
    ]
    for r in coded:
        out.append(f"### {r['name']} ({r['incident_date']})")
        out.append("")
        out.append(f"Source: {r['source_url']}")
        out.append("")
        for c in (x for x in rows if x["investigation_id"] == r["investigation_id"]):
            label = ont.factor(c["factor_curie"]).label
            out.append(f"- **{label}** ({c['evidence_type']}): \"{c['quoted_text']}\"")
        out.append("")
    out += ["## Not coded", ""]
    for r in inv:
        if r["coded"] != "yes":
            out.append(
                f"- {r['name']} ({r['incident_date']}): the fetched CSB page gives only "
                f"recommendations that do not map to a PIF without interpretation. {r['source_url']}"
            )
    out += ["", "## Codings per factor", "", "| Factor | Codings |", "| --- | --- |"]
    counts = Counter(x["factor_curie"] for x in rows)
    for curie, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        out.append(f"| {ont.factor(curie).label} | {n} |")
    assert set(by_id) >= {x["investigation_id"] for x in rows}
    return "\n".join(out) + "\n"


def main(argv: List[str]) -> int:
    text = render(Ontology.load())
    if "--write" in argv:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
